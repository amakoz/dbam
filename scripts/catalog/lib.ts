/**
 * `catalog/entry.schema.json` as it should be on disk: `z.toJSONSchema(CatalogEntrySchema)` formatted with the
 * repo's Prettier config, so the pre-commit `prettier --write` leaves it unchanged. Refinements are not part of it.
 */
export async function renderJsonSchema(): Promise<string> {
  return formatJson(z.toJSONSchema(CatalogEntrySchema), JSON_SCHEMA_PATH);
}

/** `catalog/entries/<slug>.json` for an entry, formatted like `renderJsonSchema()` so pre-commit Prettier keeps it. */
export async function renderEntryFile(entry: CatalogEntry): Promise<string> {
  return formatJson(entry, entryFilePath(entry.slug));
}

/** The entry file path for a slug. The slug must already be validated (the schema allows only `[a-z0-9-]`). */
export function entryFilePath(slug: string): string {
  return path.join(ENTRIES_DIR, `${slug}.json`);
}

async function formatJson(value: unknown, filepath: string): Promise<string> {
  const options = await prettier.resolveConfig(filepath);
  return prettier.format(JSON.stringify(value, null, 2), { ...options, filepath });
}
