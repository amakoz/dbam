import fs from "node:fs";
import path from "node:path";
import * as prettier from "prettier";
import { z } from "zod";

import { CatalogEntrySchema, type CatalogEntry } from "@/lib/catalog/schema";
import type { Database } from "@/lib/database.types";

// Shared library of the catalog CLIs (`check.ts`, `migration.ts`, `schema.ts`, `draft.ts`): loads and validates
// `catalog/entries/*.json`, renders the snapshot migration, the published JSON Schema and entry files, and finds deleted
// entries.
// Importing it has no side effects; the CLIs do the I/O orchestration and exit codes.
//
// Snapshot migrations (`supabase/migrations/<UTC yyyymmddhhmmss>_screening_catalog_snapshot.sql`) are generated by
// `renderSnapshotSql()` and never edited. Each one upserts every entry, so the table mirrors the files. The drift check
// compares the rendered body with the newest snapshot byte for byte. Deleted entries are found through the slug
// manifest: every snapshot's header lists its slugs, one `-- catalog-slug: <slug>` line each, which is simpler and
// sturdier than parsing slugs back out of the VALUES. A snapshot without a manifest is reported, not skipped.

export const REPO_ROOT = path.resolve(import.meta.dirname, "../..");
export const ENTRIES_DIR = path.join(REPO_ROOT, "catalog", "entries");
export const JSON_SCHEMA_PATH = path.join(REPO_ROOT, "catalog", "entry.schema.json");
export const MIGRATIONS_DIR = path.join(REPO_ROOT, "supabase", "migrations");

const SNAPSHOT_FILE = /^(\d{14})_screening_catalog_snapshot\.sql$/;
const MIGRATION_FILE = /^(\d{14})_.+\.sql$/;
const MANIFEST_LINE = /^-- catalog-slug: (\S+)$/gm;

/** A repo-relative path for messages, e.g. `catalog/entries/foo.json`. */
export function displayPath(file: string): string {
  return path.relative(REPO_ROOT, file).split(path.sep).join("/");
}

